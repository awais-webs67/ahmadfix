#!/bin/bash
# =====================================================================
# Ahmad Fix — copy the website from the cPanel Git repository folder
# to the live website folder. Run by cPanel ("Deploy HEAD Commit").
#
# Where does it copy to?
#   1. The DEPLOYPATH environment variable, if set
#   2. else the first line of the file ~/.deploy_path (create it if your
#      domain does not use public_html, e.g. echo "$HOME/ahmadfix.com" > ~/.deploy_path)
#   3. else ~/public_html
#
# It never deletes files on the server, so config/config.local.php
# (your database login) and config/app_key.php are always kept.
# =====================================================================
set -euo pipefail

SRC="$(cd "$(dirname "${BASH_SOURCE[0]}")" && pwd -P)"

DEST="${DEPLOYPATH:-}"
if [ -z "$DEST" ] && [ -f "$HOME/.deploy_path" ]; then
    DEST="$(head -n 1 "$HOME/.deploy_path" | tr -d '\r')"
fi
DEST="${DEST:-$HOME/public_html}"
DEST="${DEST/#\~/$HOME}"

mkdir -p "$DEST"
DEST="$(cd "$DEST" && pwd -P)"

# Repository cloned straight into the website folder: "Update from Remote" already updated it
case "$SRC/" in
    "$DEST"/*|"$DEST/")
        echo "Repository is inside the website folder ($DEST) — nothing to copy."
        exit 0
        ;;
esac

# Only what the website needs (no .git, database dump, README or this script)
ITEMS=(.htaccess index.php sitemap.php admin assets config includes lang pages)

echo "Deploying $SRC → $DEST"
for item in "${ITEMS[@]}"; do
    if [ -e "$SRC/$item" ]; then
        if command -v rsync >/dev/null 2>&1; then
            rsync -a "$SRC/$item" "$DEST/"
        else
            /bin/cp -Rf "$SRC/$item" "$DEST/"
        fi
        echo "  ✓ $item"
    fi
done

# Files that used to be static and are now generated by PHP (old copies would win otherwise)
for old in robots.txt site.webmanifest sitemap.xml; do
    if [ -f "$DEST/$old" ]; then
        mv -f "$DEST/$old" "$DEST/$old.old-backup"
        echo "  ↻ moved old $old out of the way ($old.old-backup)"
    fi
done

echo "Done. Open your website and Admin → Settings to check everything."
